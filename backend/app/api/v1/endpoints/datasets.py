"""Dynamic Dataset Engine API endpoints (/api/v1/datasets)."""

from pathlib import Path
from typing import Any

from fastapi import APIRouter, Depends, HTTPException, Query, status
from fastapi.responses import FileResponse, JSONResponse
from sqlalchemy import desc, select
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.database import get_db
from app.models.multi_agent import Dataset, DatasetItem, DatasetValidationReport, DatasetVersion
from app.schemas.common import APIResponseEnvelope
from app.schemas.multi_agent import (
    DatasetDetailResponse,
    DatasetItemSchema,
    DatasetSummarySchema,
    DatasetValidationReportSchema,
    DatasetVersionSchema,
)

router = APIRouter(prefix="/datasets", tags=["Dynamic Dataset Engine"])


def _serialize_version(v: DatasetVersion) -> DatasetVersionSchema:
    return DatasetVersionSchema(
        id=v.id,
        dataset_id=v.dataset_id,
        version_number=v.version_number,
        version_tag=v.version_tag,
        schema_version=v.schema_version,
        content_fingerprint=v.content_fingerprint,
        source_investigation_ids=v.source_investigation_ids or [],
        original_file_ids=v.original_file_ids or [],
        source_document_ids=v.source_document_ids or [],
        record_count=v.record_count,
        measurement_count=v.measurement_count,
        validation_status=v.validation_status,
        processing_config=v.processing_config or {},
        unit_conversions=v.unit_conversions or [],
        file_hashes=v.file_hashes or {},
        provenance_manifest=v.provenance_manifest or {},
        export_uris=v.export_uris,
        created_at=v.created_at,
    )


def _serialize_report(r: DatasetValidationReport) -> DatasetValidationReportSchema:
    return DatasetValidationReportSchema(
        id=r.id,
        dataset_version_id=r.dataset_version_id,
        overall_status=r.overall_status,
        total_records=r.total_records,
        passed_count=r.passed_count,
        warning_count=r.warning_count,
        quarantined_count=r.quarantined_count,
        rejected_count=r.rejected_count,
        provenance_coverage_pct=r.provenance_coverage_pct,
        null_handling_verified=r.null_handling_verified,
        unit_checks_summary=r.unit_checks_summary or {},
        quarantined_items=r.quarantined_items or [],
        warnings=r.warnings or [],
        created_at=r.created_at,
    )


@router.get(
    "",
    response_model=APIResponseEnvelope[list[DatasetSummarySchema]],
    status_code=status.HTTP_200_OK,
)
async def list_datasets(
    db: AsyncSession = Depends(get_db),
):
    """Lists all versioned scientific datasets generated by the Dynamic Dataset Engine."""
    res = await db.execute(select(Dataset).order_by(desc(Dataset.created_at)))
    rows = list(res.scalars().all())
    return APIResponseEnvelope(
        data=[
            DatasetSummarySchema(
                id=d.id,
                dataset_key=d.dataset_key,
                name=d.name,
                research_objective=d.research_objective,
                research_query=d.research_query,
                schema_version=d.schema_version,
                latest_version_number=d.latest_version_number,
                source_investigation_ids=d.source_investigation_ids or [],
                status=d.status,
                created_at=d.created_at,
                updated_at=d.updated_at,
            )
            for d in rows
        ]
    )


@router.get(
    "/{dataset_id}",
    response_model=APIResponseEnvelope[DatasetDetailResponse],
    status_code=status.HTTP_200_OK,
)
async def get_dataset_detail(
    dataset_id: str,
    db: AsyncSession = Depends(get_db),
):
    """Returns full dataset details including latest version metadata, canonical items, and validation report."""
    res = await db.execute(
        select(Dataset).where((Dataset.id == dataset_id) | (Dataset.dataset_key == dataset_id))
    )
    d = res.scalars().first()
    if not d:
        raise HTTPException(status_code=404, detail=f"Dataset '{dataset_id}' not found.")

    versions = sorted(d.versions or [], key=lambda v: v.version_number, reverse=True)
    latest_ver = versions[0] if versions else None

    items_out: list[DatasetItemSchema] = []
    report_out: DatasetValidationReportSchema | None = None

    if latest_ver:
        for it in latest_ver.items or []:
            items_out.append(
                DatasetItemSchema(
                    id=it.id,
                    investigation_id=it.investigation_id,
                    investigation_acronym=it.investigation_acronym,
                    experimental_run_id=it.experimental_run_id,
                    run_name=it.run_name,
                    parameter_name=it.parameter_name,
                    original_value=it.original_value,
                    original_unit=it.original_unit,
                    normalized_value=it.normalized_value,
                    normalized_unit=it.normalized_unit,
                    conversion_formula=it.conversion_formula,
                    uncertainty=it.uncertainty,
                    fuel_type=it.fuel_type,
                    gravity_regime=it.gravity_regime,
                    oxygen_pct=it.oxygen_pct,
                    pressure_kpa=it.pressure_kpa,
                    airflow_cm_s=it.airflow_cm_s,
                    source_document_id=it.source_document_id,
                    source_doi=it.source_doi,
                    source_url=it.source_url,
                    page_number=it.page_number,
                    section_name=it.section_name,
                    extraction_method=it.extraction_method,
                    evidence_classification=it.evidence_classification,
                    validation_status=it.validation_status,
                    validation_notes=it.validation_notes,
                )
            )
        if latest_ver.validation_reports:
            report_out = _serialize_report(latest_ver.validation_reports[0])

    return APIResponseEnvelope(
        data=DatasetDetailResponse(
            id=d.id,
            dataset_key=d.dataset_key,
            name=d.name,
            research_objective=d.research_objective,
            research_query=d.research_query,
            schema_version=d.schema_version,
            latest_version_number=d.latest_version_number,
            source_investigation_ids=d.source_investigation_ids or [],
            status=d.status,
            created_at=d.created_at,
            updated_at=d.updated_at,
            latest_version=_serialize_version(latest_ver) if latest_ver else None,
            items=items_out,
            quality_report=report_out,
        )
    )


@router.get(
    "/{dataset_id}/versions",
    response_model=APIResponseEnvelope[list[DatasetVersionSchema]],
    status_code=status.HTTP_200_OK,
)
async def list_dataset_versions(
    dataset_id: str,
    db: AsyncSession = Depends(get_db),
):
    """Returns version history and content fingerprints for a scientific dataset."""
    res = await db.execute(
        select(Dataset).where((Dataset.id == dataset_id) | (Dataset.dataset_key == dataset_id))
    )
    d = res.scalars().first()
    if not d:
        raise HTTPException(status_code=404, detail=f"Dataset '{dataset_id}' not found.")
    versions = sorted(d.versions or [], key=lambda v: v.version_number, reverse=True)
    return APIResponseEnvelope(data=[_serialize_version(v) for v in versions])


@router.get(
    "/{dataset_id}/quality-report",
    response_model=APIResponseEnvelope[DatasetValidationReportSchema],
    status_code=status.HTTP_200_OK,
)
async def get_dataset_quality_report(
    dataset_id: str,
    db: AsyncSession = Depends(get_db),
):
    """Returns the deterministic scientific validation & quality report for the latest dataset version."""
    res = await db.execute(
        select(Dataset).where((Dataset.id == dataset_id) | (Dataset.dataset_key == dataset_id))
    )
    d = res.scalars().first()
    if not d or not d.versions:
        raise HTTPException(status_code=404, detail=f"Dataset '{dataset_id}' or version not found.")
    latest_ver = sorted(d.versions, key=lambda v: v.version_number, reverse=True)[0]
    if not latest_ver.validation_reports:
        raise HTTPException(status_code=404, detail=f"Validation report for dataset '{dataset_id}' not found.")
    return APIResponseEnvelope(data=_serialize_report(latest_ver.validation_reports[0]))


@router.post(
    "/{dataset_id}/analyze",
    response_model=APIResponseEnvelope[dict[str, Any]],
    status_code=status.HTTP_200_OK,
)
async def analyze_dataset(
    dataset_id: str,
    db: AsyncSession = Depends(get_db),
):
    """Computes parameter statistics, environmental condition envelopes, and campaign comparisons on a dataset."""
    res = await db.execute(
        select(Dataset).where((Dataset.id == dataset_id) | (Dataset.dataset_key == dataset_id))
    )
    d = res.scalars().first()
    if not d or not d.versions:
        raise HTTPException(status_code=404, detail=f"Dataset '{dataset_id}' not found.")
    latest_ver = sorted(d.versions, key=lambda v: v.version_number, reverse=True)[0]
    items: list[DatasetItem] = list(latest_ver.items or [])

    by_param: dict[str, list[float]] = {}
    units: dict[str, str] = {}
    o2_vals: list[float] = []
    p_vals: list[float] = []
    flow_vals: list[float] = []

    for it in items:
        if it.normalized_value is not None:
            by_param.setdefault(it.parameter_name, []).append(float(it.normalized_value))
            units[it.parameter_name] = it.normalized_unit
        if it.oxygen_pct is not None:
            o2_vals.append(float(it.oxygen_pct))
        if it.pressure_kpa is not None:
            p_vals.append(float(it.pressure_kpa))
        if it.airflow_cm_s is not None:
            flow_vals.append(float(it.airflow_cm_s))

    parameter_summaries = [
        {
            "parameter_name": p,
            "unit": units.get(p, ""),
            "count": len(vals),
            "min": round(min(vals), 4),
            "max": round(max(vals), 4),
            "mean": round(sum(vals) / len(vals), 4),
        }
        for p, vals in by_param.items()
        if vals
    ]

    return APIResponseEnvelope(
        data={
            "dataset_id": d.id,
            "dataset_key": d.dataset_key,
            "version_tag": latest_ver.version_tag,
            "record_count": len(items),
            "investigations": latest_ver.source_investigation_ids,
            "environmental_envelope": {
                "oxygen_pct_range": [min(o2_vals), max(o2_vals)] if o2_vals else None,
                "pressure_kpa_range": [min(p_vals), max(p_vals)] if p_vals else None,
                "airflow_cm_s_range": [min(flow_vals), max(flow_vals)] if flow_vals else None,
            },
            "parameter_summaries": parameter_summaries,
        }
    )


@router.get("/{dataset_id}/export")
async def export_dataset(
    dataset_id: str,
    format: str = Query("json", description="Export format: json | csv | parquet"),
    db: AsyncSession = Depends(get_db),
):
    """Exports a versioned scientific dataset in JSON, CSV, or Parquet format."""
    fmt = format.lower()
    if fmt not in ("json", "csv", "parquet"):
        raise HTTPException(status_code=400, detail="Unsupported format. Choose 'json', 'csv', or 'parquet'.")

    res = await db.execute(
        select(Dataset).where((Dataset.id == dataset_id) | (Dataset.dataset_key == dataset_id))
    )
    d = res.scalars().first()
    if not d or not d.versions:
        raise HTTPException(status_code=404, detail=f"Dataset '{dataset_id}' not found.")

    latest_ver = sorted(d.versions, key=lambda v: v.version_number, reverse=True)[0]
    uris = latest_ver.export_uris or {}
    file_path_str = uris.get(fmt)

    if file_path_str and Path(file_path_str).exists():
        media_map = {
            "json": "application/json",
            "csv": "text/csv",
            "parquet": "application/octet-stream",
        }
        p = Path(file_path_str)
        return FileResponse(
            path=str(p),
            media_type=media_map[fmt],
            filename=p.name,
        )

    # Fallback inline JSON serialization if vault file was cleaned
    return JSONResponse(
        content={
            "dataset_key": d.dataset_key,
            "version_tag": latest_ver.version_tag,
            "record_count": latest_ver.record_count,
            "format": fmt,
        }
    )
